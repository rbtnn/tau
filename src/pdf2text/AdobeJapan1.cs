        static readonly object lockObj = new object();

        /// <summary>CID を Unicode に変換する。分からなければ -1。</summary>
        public static int ToUnicode(int cid)
        {
            Dictionary<int, int> m = Table();
            return m.TryGetValue(cid, out int u) ? u : -1;
        }

        /// <summary>CID を文字列に変換する。分からなければ null。</summary>
        public static string ToText(int cid)
        {
            int u = ToUnicode(cid);
            if (u < 0 || u > 0x10FFFF) return null;
            if (u >= 0xD800 && u <= 0xDFFF) return null;
            if (u > 0xFFFF) return char.ConvertFromUtf32(u);
            return ((char)u).ToString();
        }

        static Dictionary<int, int> Table()
        {
            lock (lockObj)
            {
                if (map != null) return map;

                byte[] raw = Convert.FromBase64String(Encoded);
                map = new Dictionary<int, int>(16000);

                int i = 0;
                int cid = 0;
                int uni = 0;
                while (i < raw.Length)
                {
                    int dc = ReadVarint(raw, ref i);
                    int du = ReadVarint(raw, ref i);
                    cid += dc;
                    uni += du;
                    map[cid] = uni;
                }
                return map;
            }
        }

        // zigzag エンコードされた可変長整数
        static int ReadVarint(byte[] raw, ref int i)
        {
            uint z = 0;
            int shift = 0;
            while (i < raw.Length)
            {
                byte b = raw[i++];
                z |= (uint)(b & 0x7F) << shift;
                if ((b & 0x80) == 0) break;
                shift += 7;
            }
            // zigzag を戻す
            return (int)(z >> 1) ^ -(int)(z & 1);
        }

